"""Synthetic training rooms for the layout model.

Renders 360 photos (1024 x 512, equirectangular) of randomly generated rooms with the exact
corner labels the model trains on. Everything here is generated by us, so the data has no
licence strings attached, unlike the public research datasets (Structured3D, ZInD), which
forbid commercial use.

It is a starting point only: the model learns the geometry here (walls are straight, the floor
line continues behind furniture). It learns what real Danish homes look like from Polygon's own
photos (export_polyplan.py).

    python synth.py --out data/synth --n 20000 --seed 1
"""
import argparse, os, math
import numpy as np
from PIL import Image

W, H = 1024, 512


def rand_room(rng):
    """A Manhattan room outline (metres, counter-clockwise): a rectangle, or an L when lucky."""
    a, b = rng.uniform(1.6, 7.5), rng.uniform(1.4, 6.0)
    if rng.random() < 0.65:
        return np.array([[0, 0], [a, 0], [a, b], [0, b]], float)
    ca, cb = rng.uniform(0.25, 0.6) * a, rng.uniform(0.25, 0.6) * b   # cut a corner off: L shape
    return np.array([[0, 0], [a, 0], [a, b - cb], [a - ca, b - cb], [a - ca, b], [0, b]], float)


def inside(poly, p):
    c = False
    for i in range(len(poly)):
        a, b = poly[i], poly[i - 1]
        if (a[1] > p[1]) != (b[1] > p[1]) and p[0] < (b[0] - a[0]) * (p[1] - a[1]) / (b[1] - a[1]) + a[0]:
            c = not c
    return c


def ray_walls(poly, cam, dx, dy):
    """Distance along each ray (dx, dy unit vectors, any shape) to the nearest wall, and which wall."""
    t = np.full(dx.shape, np.inf); idx = np.full(dx.shape, -1)
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]
        ex, ey = q[0] - p[0], q[1] - p[1]
        den = dx * ey - dy * ex
        with np.errstate(divide='ignore', invalid='ignore'):
            tt = ((p[0] - cam[0]) * ey - (p[1] - cam[1]) * ex) / den
            s = ((p[0] - cam[0]) * dy - (p[1] - cam[1]) * dx) / den
        ok = (tt > 1e-6) & (s >= 0) & (s <= 1) & (tt < t)
        t = np.where(ok, tt, t); idx = np.where(ok, i, idx)
    return t, idx


def texture(rng, kind, u, v):
    """Cheap procedural surface: base colour, planks or tiles on floors, slight noise."""
    base = rng.uniform(0.25, 0.95, 3) if kind != 'floor' else rng.uniform(0.15, 0.7, 3)
    if kind == 'wall' and rng.random() < 0.6:
        base = np.full(3, rng.uniform(0.75, 0.95)) * rng.uniform(0.95, 1.05, 3)   # most walls are white-ish
    col = np.ones(u.shape + (3,)) * base
    if kind in ('floor', 'ceiling') and rng.random() < 0.6:
        w = rng.uniform(0.1, 0.25)                                  # planks
        band = np.floor(u / w); col *= (0.88 + 0.12 * np.cos(band * 12.9898) [..., None] ** 2)
    if kind == 'floor' and rng.random() < 0.3:
        s = rng.uniform(0.2, 0.6)                                   # tiles
        col *= np.where(((np.floor(u / s) + np.floor(v / s)) % 2)[..., None] == 0, 1.0, 0.85)
    return col


def render(rng):
    poly = rand_room(rng)
    room_h = rng.uniform(2.25, 3.1); cam_h = rng.uniform(1.0, 1.8)
    for _ in range(100):                                            # camera inside, away from walls, all corners in view
        cam = np.array([rng.uniform(0.3, poly[:, 0].max() - 0.3), rng.uniform(0.3, poly[:, 1].max() - 0.3)])
        if not inside(poly, cam):
            continue
        d = poly - cam; dist = np.hypot(d[:, 0], d[:, 1])
        tt, _ = ray_walls(poly, cam, d[:, 0] / dist, d[:, 1] / dist)
        if np.all(np.abs(tt - dist) < 1e-3) and dist.min() > 0.35:
            break
    else:
        return None
    yaw0 = rng.uniform(0, 2 * math.pi)
    u = (np.arange(W) + 0.5) / W; v = (np.arange(H) + 0.5) / H
    U, V = np.meshgrid(u, v)
    yaw = (U - 0.5) * 2 * math.pi + yaw0; pit = (0.5 - V) * math.pi
    dx, dy, dz = np.sin(yaw) * np.cos(pit), np.cos(yaw) * np.cos(pit), np.sin(pit)
    th, wi = ray_walls(poly, cam, np.sin(yaw), np.cos(yaw))       # horizontal distance to the wall in each column
    t_wall = th / np.maximum(np.cos(pit), 1e-6)
    with np.errstate(divide='ignore'):
        t_floor = np.where(dz < 0, -cam_h / dz, np.inf); t_ceil = np.where(dz > 0, (room_h - cam_h) / dz, np.inf)
    t = np.minimum.reduce([t_wall, t_floor, t_ceil])
    px, py, pz = cam[0] + dx * t, cam[1] + dy * t, cam_h + dz * t
    surf = np.where(t == t_floor, 0, np.where(t == t_ceil, 1, 2))
    img = np.zeros((H, W, 3))
    img = np.where((surf == 0)[..., None], texture(rng, 'floor', px, py), img)
    img = np.where((surf == 1)[..., None], texture(rng, 'ceiling', px, py), img)
    walls = [texture(rng, 'wall', np.hypot(px, py), pz) for _ in range(len(poly))] if rng.random() < 0.3 else [texture(rng, 'wall', np.hypot(px, py), pz)] * len(poly)
    for i, wt in enumerate(walls):
        img = np.where(((surf == 2) & (wi == i))[..., None], wt, img)
    # skirting boards, doors and windows on the walls
    if rng.random() < 0.6:
        img = np.where(((surf == 2) & (pz < 0.08))[..., None], rng.uniform(0.3, 1.0, 3), img)
    seg_s = np.zeros_like(px)
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]; L = np.hypot(*(q - p))
        seg_s = np.where(wi == i, ((px - p[0]) * (q[0] - p[0]) + (py - p[1]) * (q[1] - p[1])) / L, seg_s)
        for _ in range(rng.integers(0, 3)):
            if L < 1.2:
                break
            w = rng.uniform(0.7, min(1.6, L - 0.3)); s0 = rng.uniform(0.15, L - w - 0.15); door = rng.random() < 0.5
            z0, z1 = (0, rng.uniform(1.95, 2.1)) if door else (rng.uniform(0.6, 1.0), rng.uniform(1.8, 2.2))
            m = (surf == 2) & (wi == i) & (seg_s > s0) & (seg_s < s0 + w) & (pz > z0) & (pz < min(z1, room_h - 0.05))
            img = np.where(m[..., None], rng.uniform(0.05, 0.4, 3) if door else rng.uniform(0.7, 1.0, 3), img)
    # furniture: boxes standing on the floor (they hide parts of the floor line, which is the point)
    zbuf = t.copy()
    for _ in range(rng.integers(0, 7)):
        bw, bd, bh = rng.uniform(0.3, 2.2), rng.uniform(0.3, 0.9), rng.uniform(0.3, 2.2)
        k = rng.integers(len(poly)); p, q = poly[k], poly[(k + 1) % len(poly)]; L = np.hypot(*(q - p))
        if L < bw + 0.1:
            continue
        e = (q - p) / L; nrm = np.array([-e[1], e[0]]); s0 = rng.uniform(0, L - bw)
        c = [p + e * s0, p + e * (s0 + bw), p + e * (s0 + bw) + nrm * bd, p + e * s0 + nrm * bd]
        if not inside(poly, c[2]) or not inside(poly, c[3]) or inside(np.array(c), cam):
            continue
        x0, x1 = min(a[0] for a in c), max(a[0] for a in c); y0, y1 = min(a[1] for a in c), max(a[1] for a in c)
        with np.errstate(divide='ignore', invalid='ignore'):
            tx0, tx1 = (x0 - cam[0]) / dx, (x1 - cam[0]) / dx; ty0, ty1 = (y0 - cam[1]) / dy, (y1 - cam[1]) / dy; tz0, tz1 = (0 - cam_h) / dz, (bh - cam_h) / dz
        tn = np.maximum.reduce([np.minimum(tx0, tx1), np.minimum(ty0, ty1), np.minimum(tz0, tz1)])
        tf = np.minimum.reduce([np.maximum(tx0, tx1), np.maximum(ty0, ty1), np.maximum(tz0, tz1)])
        m = (tn <= tf) & (tn > 0) & (tn < zbuf)
        zbuf = np.where(m, tn, zbuf); img = np.where(m[..., None], rng.uniform(0.05, 0.9, 3) * rng.uniform(0.85, 1.0, (H, W, 1)), img)
    # light: a soft lamp plus ambient, then camera noise and exposure
    lamp = np.array([rng.uniform(poly[:, 0].min(), poly[:, 0].max()), rng.uniform(poly[:, 1].min(), poly[:, 1].max()), room_h - 0.2])
    hx, hy, hz = cam[0] + dx * zbuf, cam[1] + dy * zbuf, cam_h + dz * zbuf
    dl = np.sqrt((hx - lamp[0]) ** 2 + (hy - lamp[1]) ** 2 + (hz - lamp[2]) ** 2)
    img = img * (rng.uniform(0.35, 0.7) + rng.uniform(0.3, 0.8) / (1 + 0.25 * dl * dl))[..., None]
    img = img * rng.uniform(0.55, 1.05) + rng.normal(0, rng.uniform(0.005, 0.03), img.shape)
    img = np.clip(img, 0, 1) ** rng.uniform(0.8, 1.25)
    # labels: each corner's column, with its ceiling and floor row, in HorizonNet's text format
    cors = []
    for c in poly:
        d = c - cam; dist = np.hypot(*d); y = math.atan2(d[0], d[1]) - yaw0
        x = ((y / (2 * math.pi) + 0.5) % 1) * W - 0.5
        yc = (0.5 - math.atan2(room_h - cam_h, dist) / math.pi) * H - 0.5
        yf = (0.5 + math.atan2(cam_h, dist) / math.pi) * H - 0.5
        cors.append((x, yc, yf))
    cors.sort()
    return (img * 255).astype(np.uint8), cors, dict(room=poly.tolist(), cam=cam.tolist(), cam_h=cam_h, room_h=room_h, yaw0=yaw0)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--out', required=True); ap.add_argument('--n', type=int, default=1000); ap.add_argument('--seed', type=int, default=0)
    a = ap.parse_args(); rng = np.random.default_rng(a.seed)
    os.makedirs(os.path.join(a.out, 'img'), exist_ok=True); os.makedirs(os.path.join(a.out, 'label_cor'), exist_ok=True)
    k = 0
    while k < a.n:
        r = render(rng)
        if r is None:
            continue
        img, cors, _ = r; name = 'synth_%06d_%06d' % (a.seed, k)
        Image.fromarray(img).save(os.path.join(a.out, 'img', name + '.png'))
        with open(os.path.join(a.out, 'label_cor', name + '.txt'), 'w') as f:
            for x, yc, yf in cors:
                f.write('%.2f %.2f\n%.2f %.2f\n' % (x, yc, x, yf))
        k += 1
        if k % 100 == 0:
            print(k, 'rooms')
